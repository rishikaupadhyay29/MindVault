import { JSDOM, VirtualConsole } from "jsdom";
const errors = []; const vc = new VirtualConsole();
vc.on("jsdomError", e => errors.push(String(e.message).slice(0,160))); vc.on("error", e => errors.push(String(e).slice(0,160)));
const ctx = () => new Proxy({}, { get: () => () => ({ addColorStop() {} }), set: () => true });
const dom = await JSDOM.fromURL("http://localhost:8000/", { runScripts: "dangerously", resources: "usable", pretendToBeVisual: true, virtualConsole: vc,
  beforeParse(w) { w.fetch = (u, o) => fetch(new URL(u, "http://localhost:8000").href, o); w.HTMLCanvasElement.prototype.getContext = ctx;
    w.matchMedia = () => ({ matches: false }); w.TextDecoder = TextDecoder; w.confirm = () => true; } });
const w = dom.window, d = w.document, $ = s => d.querySelector(s), sleep = ms => new Promise(r => setTimeout(r, ms));
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) process.exitCode = 1; };
await sleep(800);
ok($("#auth").style.display === "grid" && $("#shell").style.display === "none", "unauthenticated user sees the login screen");
$("#ae").value = "khushi@example.com"; $("#ap").value = "wrong-password"; w.authSubmit(); await sleep(800);
ok(/incorrect/i.test($("#aerr").textContent), "wrong password shows an error: " + $("#aerr").textContent);
$("#ap").value = "correct-horse"; w.authSubmit(); await sleep(1500);
ok($("#shell").style.display === "" && $("#pname").textContent.startsWith("Khushi"), "login shows the app for Khushi");
ok($("#m1").textContent === "5" && $("#m2").textContent === "4", `dashboard metrics from DB: entries=${$("#m1").textContent} chunks=${$("#m2").textContent}`);
ok($("#recent").textContent.includes("Postgres") || $("#recent").textContent.includes("guide"), "recent knowledge cards rendered");
w.go("library"); await sleep(800);
ok($("#notes").querySelectorAll(".card").length === 5, "library lists 5 notes (cards: " + $("#notes").querySelectorAll(".card").length + ")");
ok($("#notes").textContent.includes("Couldn’t index"), "failed note shows a Retry state");
$("#notes .bad a").click(); await sleep(3000); await w.loadLibrary();
ok(!$("#notes").textContent.includes("Couldn’t index"), "Retry recovered the failed note");
w.newNote(); $("#nti").value = "UI note"; $("#ntg").value = "ui, test"; $("#nbody").value = "# Heading\n\nPostgreSQL replication copies data."; await w.saveNote(); await sleep(2800);
ok(/Indexed · \d chunk/.test($("#nst").textContent), "editor shows Indexed after save: " + $("#nst").textContent);
w.togglePrev(); ok($("#nprev").innerHTML.includes("<h2>Heading</h2>"), "markdown preview renders heading");
w.closeNote(); await sleep(500);
ok($("#tags").textContent.includes("ui 1"), "tag filter chips include new tag");
w.go("search"); $("#sq").value = "how to make database queries faster"; $("#sq").dispatchEvent(new w.Event("input")); await sleep(1500);
ok($("#sres").querySelectorAll(".res").length >= 1 && /Similarity 0\.\d\d/.test($("#sres").textContent), "semantic search renders results with similarity");
w.go("companion"); await sleep(500); $("#cq").value = "How do database indexes speed up queries?"; await w.send(); await sleep(800);
ok($("#chat").textContent.includes("speed up queries") && $("#chat").querySelector(".src"), "AI Companion streamed an answer with a source chip");
w.go("universe"); await sleep(900);
ok(/notes/.test($("#uhint").textContent), "universe loaded: " + $("#uhint").textContent);
w.go("diagnostics"); await sleep(900);
ok($("#diag").textContent.includes("pgvector") && $("#diag").textContent.includes("HNSW"), "diagnostics lists services");
w.go("settings"); await sleep(400);
ok($("#sdn").value.startsWith("Khushi") && $("#sem").value === "khushi@example.com", "settings populated from account");
$("#sdn").value = "Khushi M"; await w.saveProfile(); await sleep(500);
ok($("#pname").textContent === "Khushi M", "profile update persists to the UI");
ok(errors.length === 0, "no script errors" + (errors.length ? ": " + errors.join(" | ") : ""));
process.exit(process.exitCode || 0);
